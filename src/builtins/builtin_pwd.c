#include "minishell.h"

int	builtin_pwd(void)
{
	char	cwd[4096];

	if (getcwd(cwd, sizeof(cwd)) == NULL)
	{
		print_error("pwd", "error retrieving current directory");
		return (1);
	}
	ft_putendl_fd(cwd, 1);
	return (0);
}
